import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { chromium } from "playwright";
import { createServer } from "vite";
import { restoreModelId } from "../../shared/image-restore.js";
import { makeNode } from "../../shared/studio.js";

test("修复滑杆可在画布缩放下拖至两端，切换版本使用当时的原图", async (t) => {
  const dir = await mkdtemp(path.join(tmpdir(), "studio-restore-"));
  process.env.STUDIO_DATA_DIR = dir;
  t.after(() => rm(dir, { recursive: true, force: true }));
  const vite = await createServer({ server: { port: 0, strictPort: false, hmr: false }, logLevel: "error" });
  await vite.listen();
  t.after(() => vite.close());
  const base = vite.resolvedUrls.local[0];
  const browser = await chromium.launch();
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" });
  page.setDefaultTimeout(5000);
  const source = makeNode("image", { x: 0, y: 0 }, { assetId: "flare" });
  const result = makeNode("image", { x: 455, y: 0 }, { imageModel: restoreModelId, assetId: "operator" });
  const reused = makeNode("image", { x: 0, y: 300 }, { assetId: "receiver", imageModel: "other-model" });
  const board = await (await page.request.post(base + "api/projects", { data: { board: {
    name: "修复对比", nodes: [source, result, reused], edges: [{ id: "wire", source: source.id, target: result.id }], order: [],
  } } })).json();
  const job = { project: board.id, type: "image", nodeId: result.id, status: "done", created: new Date().toISOString() };
  await writeFile(path.join(dir, "jobs.json"), JSON.stringify([
    { ...job, id: "old-format", detail: "高清修复 · 细节增强 42% · 长边 3072 px", inputAssetIds: ["coast"], assetId: "operator" },
    { ...job, id: "older-version", modelId: restoreModelId, inputAssetIds: ["flare"], assetId: "receiver" },
  ]));
  await page.route("**/api/engine", r => r.fulfill({ json: { online: false } }));
  await page.goto(base + "#project/" + board.id + "?node=" + result.id);
  const node = page.locator('.react-flow__node[data-id="' + result.id + '"]');
  const slider = node.getByRole("slider", { name: "修复前后对比" });
  const original = node.getByAltText("修复前的原图");
  await slider.waitFor();
  const files = node.getByRole("group", { name: "文件操作" });
  const downloadLink = files.getByRole("link", { name: "下载图片" });
  assert.equal(await downloadLink.getAttribute("href"), "/stills/operator.jpg");
  await page.route("**/api/assets/operator/folder", r => r.fulfill({ json: { opened: true } }));
  const openRequest = page.waitForRequest("**/api/assets/operator/folder");
  await files.getByRole("button", { name: "打开文件位置" }).click();
  assert.equal((await openRequest).postDataJSON().projectId, board.id);
  await page.locator('.react-flow__node[data-id="' + reused.id + '"]').getByRole("slider").waitFor();
  assert.equal(await page.locator('.react-flow__node[data-id="' + source.id + '"]').getByRole("slider").count(), 0);
  assert.equal(await original.getAttribute("src"), "/stills/coast.jpg");
  await page.getByRole("button", { name: "放大", exact: true }).click();
  await slider.hover();
  const frame = await node.locator(".restore-comparison").boundingBox();
  const handle = await slider.boundingBox();
  const y = handle.y + handle.height / 2;
  const transform = () => node.evaluate(el => [el.style.transform, el.closest(".react-flow__viewport").style.transform]);
  const position = await transform();
  const drag = async (fraction) => page.mouse.move(frame.x + frame.width * fraction, y, { steps: 6 });
  await page.mouse.move(handle.x + handle.width / 2, y);
  await page.mouse.down();
  await drag(-0.02);
  assert.equal(await slider.getAttribute("aria-valuenow"), "0");
  assert.equal(await original.evaluate(el => getComputedStyle(el).clipPath), "inset(0px 0px 0px 0%)");
  await drag(1.02);
  await page.mouse.up();
  assert.equal(await slider.getAttribute("aria-valuenow"), "100");
  assert.equal(await original.evaluate(el => getComputedStyle(el).clipPath), "inset(0px 0px 0px 100%)");
  await slider.press("Home");
  await slider.press("Shift+ArrowRight");
  assert.equal(await slider.getAttribute("aria-valuenow"), "10");
  assert.equal(await slider.evaluate(el => el.matches(":focus-visible")), true);
  const gripStyle = await slider.locator(".restore-grip").evaluate(el => {
    const { outlineStyle, boxShadow } = getComputedStyle(el);
    return [outlineStyle, boxShadow];
  });
  assert.deepEqual(gripStyle, ["none", "none"]);
  assert.deepEqual(await transform(), position);
  await page.getByRole("button", { name: /生成记录/ }).click();
  await page.getByRole("button", { name: /历史版本/ }).click();
  assert.equal(await page.getByRole("dialog").getByRole("link", { name: "下载图片" }).getAttribute("href"), "/stills/receiver.jpg");
  await page.getByRole("button", { name: "使用这个版本" }).click();
  await slider.waitFor();
  assert.equal(await original.getAttribute("src"), "/stills/flare.jpg");
  assert.equal(await slider.getAttribute("aria-valuenow"), "72");
  await page.getByRole("button", { name: "对比原图", exact: true }).click();
  const viewer = page.getByRole("dialog");
  const largeSlider = viewer.getByRole("slider", { name: "修复前后对比" });
  await largeSlider.waitFor();
  assert.equal(await viewer.getByRole("link", { name: "下载图片" }).getAttribute("href"), "/stills/receiver.jpg");
  assert.equal(await largeSlider.getAttribute("aria-valuenow"), "50");
  assert.equal(await viewer.getByAltText("修复前的原图").getAttribute("src"), "/stills/flare.jpg");
  const large = await largeSlider.boundingBox();
  assert.ok(large.width > frame.width && large.height > frame.height);
  await page.mouse.move(large.x + large.width * .25, large.y + large.height * .25);
  await page.mouse.down();
  assert.ok(Math.abs(Number(await largeSlider.getAttribute("aria-valuenow")) - 25) <= 1);
  await page.mouse.move(large.x + large.width, large.y + large.height * .25);
  await page.mouse.up();
  assert.equal(await largeSlider.getAttribute("aria-valuenow"), "100");
  await viewer.getByRole("button", { name: "100%", exact: true }).click();
  const natural = viewer.locator(".restore-comparison img").first();
  assert.ok(await natural.evaluate(el => Math.abs(el.getBoundingClientRect().width - el.naturalWidth) < 1));
  await viewer.getByRole("button", { name: "适应窗口" }).click();
  assert.equal(await largeSlider.getAttribute("aria-valuenow"), "100");
  await largeSlider.press("Escape");
  await viewer.waitFor({ state: "hidden" });
  assert.equal(await slider.getAttribute("aria-valuenow"), "72");
  await page.goto(base + "#project/" + board.id + "?node=" + result.id + "&view=compare");
  await viewer.getByRole("slider", { name: "修复前后对比" }).waitFor();
});

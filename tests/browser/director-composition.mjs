import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { chromium } from "playwright";
import { createServer } from "vite";
import { makeNode } from "../../shared/studio.js";
import { canvasInputs, resolveImages } from "../../shared/canvas.js";
import { assetBindings } from "../../server/asset-library.mjs";

test("画布背景、群演和人物设定从机位构图接入图片与视频分镜", async t => {
  const dir = await mkdtemp(path.join(tmpdir(),"studio-composition-"));
  process.env.STUDIO_DATA_DIR = dir;
  t.after(() => rm(dir,{recursive:true,force:true}));
  const vite = await createServer({server:{port:0,strictPort:false,hmr:false},logLevel:"error"});
  t.after(() => vite.close()); await vite.listen();
  const browser = await chromium.launch({args:["--use-angle=swiftshader","--enable-unsafe-swiftshader"]});
  t.after(() => browser.close());
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  page.setDefaultTimeout(12000);
  const errors = [];
  page.on("pageerror",e => errors.push(e.message));
  const base = vite.resolvedUrls.local[0];
  const scene = makeNode("image",{x:0,y:0},{title:"海岸布景",assetId:"coast"});
  const portrait = makeNode("image",{x:0,y:260},{title:"主角设定",assetId:"operator"});
  const res = await page.request.post(base+"api/projects",{data:{board:{name:"构图练习",nodes:[scene,portrait],edges:[],order:[]}}});
  assert.equal(res.status(),201);
  const board = await res.json(), endpoint = base+"api/projects/"+board.id;
  const button = name => page.getByRole("button",{name,exact:true});
  await page.goto(base+"#project/"+board.id);
  await page.locator('.react-flow__node[data-id="'+scene.id+'"]').click();
  await button("搭景").click();
  await button("放大机位监看").waitFor();
  const combo = name => page.getByRole("combobox",{name,exact:true});
  await combo("角色参考图").click();
  await page.getByRole("option",{name:"主角设定",exact:true}).click();
  await button("近景").click();
  await page.getByText("已调整当前机位",{exact:true}).waitFor();
  await button("撤销").click();
  await button("布置群演").click();
  await button("交错排列").click();
  await button("放入场景").click();
  await button("群演 6").waitFor();
  await button("撤销").click();
  assert.equal(await button("群演 1").count(),0);
  await button("重做").click();
  await button("群演 6").click();
  await page.getByRole("textbox",{name:"对象名称"}).fill("路人");
  await page.getByRole("textbox",{name:"对象名称"}).press("Tab");
  await button("路人").waitFor();
  await page.locator(".ds-object").filter({hasText:"机位 1"}).click();
  await button("全体角色同框").click();
  await combo("背景投影").click();
  await page.getByRole("option",{name:"360° 全景",exact:true}).click();
  await page.waitForFunction(()=>document.querySelector(".ds-status")?.textContent==="已保存");
  if (process.env.COMPOSITION_STAGE_SCREENSHOT) await page.screenshot({path:process.env.COMPOSITION_STAGE_SCREENSHOT});
  for (const kind of ["image","video"]) {
    if (kind === "video") {
      const saved = await (await page.request.get(endpoint)).json();
      const stage = saved.nodes.find(n => n.data.kind==="stage");
      await page.reload();
      await page.locator('.react-flow__node[data-id="'+stage.id+'"]').dblclick();
      if (!(await button("构图出片").count())) await button("打开导演台").click();
    }
    await button("构图出片").click();
    const img = page.getByRole("img",{name:"当前机位的构图截图"});
    await img.waitFor();
    assert.ok(await img.evaluate(el => el.decode().then(()=>el.naturalWidth===1920)));
    if (kind === "video") await button("视频分镜").click();
    if (process.env.COMPOSITION_TAKE_SCREENSHOT && kind === "image") await page.screenshot({path:process.env.COMPOSITION_TAKE_SCREENSHOT});
    await button("创建分镜节点").click();
    await page.getByRole("dialog",{name:"3D 导演台"}).waitFor({state:"detached"});
    const saved = await (await page.request.get(endpoint)).json();
    const stage = saved.nodes.find(n => n.data.kind==="stage");
    assert.equal(stage.data.stage.backgroundMode,"panorama");
    assert.equal(stage.data.stage.objects.filter(o=>o.type==="actor").length,7);
    assert.ok([...assetBindings(saved).values()].includes("operator"));
    const target = saved.nodes.find(n => n.data.title===(kind==="image" ? "构图生图" : "构图生视频"));
    assert.equal(target.data.kind,kind);
    const assets = await (await page.request.get(base+"api/assets")).json();
    const refs = resolveImages(canvasInputs(saved,target,assets),target,assets,{kind,maxRefs:4});
    assert.equal(refs.error,"");
    assert.deepEqual(refs.selected.map(r=>r.assetId),[stage.data.assetId,"operator","coast"]);
    assert.match(target.data.text,/角色 1.*@图2/u);
    assert.deepEqual(saved.edges.filter(e => e.target===target.id).map(e => e.source),[target.data.imageRefOrder[0],portrait.id,scene.id]);
  }
  assert.deepEqual(errors,[]);
});

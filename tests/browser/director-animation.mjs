import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { chromium } from "playwright";
import { createServer } from "vite";
import { makeNode } from "../../shared/studio.js";
import { stageObject } from "../../shared/director-stage.js";

test("用画布参考搭景、摆放模型、预览走位和运镜并重新打开", async t => {
  const dir = await mkdtemp(path.join(tmpdir(),"studio-stage-animation-"));
  process.env.STUDIO_DATA_DIR = dir;
  t.after(() => rm(dir,{recursive:true,force:true}));
  const vite = await createServer({server:{port:0,hmr:false,strictPort:false},logLevel:"error"});
  t.after(() => vite.close()); await vite.listen();
  const browser = await chromium.launch({args:["--use-angle=swiftshader","--enable-unsafe-swiftshader"]});
  t.after(() => browser.close());
  const page = await browser.newPage({viewport:{width:1380,height:870}});
  page.setDefaultTimeout(9000);
  const errors = [];
  page.on("pageerror",e => errors.push(e.message));
  const base = vite.resolvedUrls.local[0];
  const stage = makeNode("stage",{x:0,y:0});
  const ref = makeNode("image",{x:-440,y:0},{title:"场景图",assetId:"coast"});
  const portrait = makeNode("image",{x:-440,y:260},{title:"人物图",assetId:"operator"});
  const response = await page.request.post(base+"api/projects",{data:{board:{name:"走位与运镜",nodes:[stage,ref,portrait],
    edges:[{id:"a-b",source:ref.id,target:stage.id}],order:[]}}});
  const board = await response.json(), endpoint = base+"api/projects/"+board.id;
  assert.equal(response.status(),201,JSON.stringify(board));
  const actor = {...stageObject("actor"),name:"访客"}, camera = {...stageObject("camera"),name:"全景"};
  const prop = {...stageObject("prop"),name:"靠背椅",shape:"chair",size:[.5,.92,.53],position:[1,0,0]};
  let writes = 0;
  page.on("request",req => { if (req.url() === endpoint && req.method() === "PUT") writes++; });
  await page.route("**/api/prompt-models",route => route.fulfill({json:[{id:"vision",name:"视觉测试",model:"local-vision"}]}));
  await page.route("**/director-scene",route => {
    assert.deepEqual(route.request().postDataJSON(),{assetIds:["coast","operator"],profileId:"vision",note:"门边有一把椅子"});
    return route.fulfill({json:{objects:[actor,prop,camera],cameraId:camera.id,referenceIds:["coast","operator"]}});
  });
  const button = name => page.getByRole("button",{name,exact:true});
  const save = () => page.waitForFunction(() => document.querySelector(".ds-status")?.textContent === "已保存");
  await page.goto(base+"#project/"+board.id);
  await button("打开导演台").click();
  await button("AI 识图搭景").click();
  assert.equal(await button("选择参考图 场景图").getAttribute("aria-pressed"),"true");
  await button("选择参考图 人物图").click();
  await page.getByLabel("搭景要求").fill("门边有一把椅子");
  await button("识图搭景").click();
  await button("应用搭景草案").click();
  await button("布景模型库").click();
  if (process.env.DIRECTOR_ANIMATION_QA) {
    await page.locator(".ds-model-grid img").first().waitFor();
    await page.screenshot({path:path.join(path.dirname(process.env.DIRECTOR_ANIMATION_QA),"director-models.png")});
  }
  await button("摆放木桌").click();
  assert.equal(await page.getByLabel("对象名称").inputValue(),"木桌");
  await page.locator(".ds-object").filter({hasText:"访客"}).click();
  await button("动画时间轴").click();
  await button("记录关键帧").click();
  const head = page.getByLabel("时间轴播放头"), x = page.getByLabel("位置 X",{exact:true});
  await head.press("End");
  await x.fill("4"); await x.press("Enter");
  const ruler = await head.boundingBox();
  await page.mouse.click(ruler.x+ruler.width/2,ruler.y+ruler.height/2);
  await page.waitForFunction(() => document.querySelector('[aria-label="位置 X"]').value === "2");
  await head.press("Home");
  await button("运镜").click();
  await page.getByRole("combobox",{name:"运镜方式"}).click();
  await page.getByRole("option",{name:"向右绕拍",exact:true}).click();
  await button("从 0.00 s 添加运镜").click();
  await button("全景 第 48 帧").waitFor();
  await button("机位视角").click();
  await save(); const savedWrites = writes;
  await button("播放").click();
  await page.waitForFunction(() => Number(document.querySelector('[aria-label="时间轴播放头"]').value)>10);
  await button("暂停").click();
  assert.equal(writes,savedWrites);
  await button("导演视角").click();
  if (process.env.DIRECTOR_ANIMATION_QA) await page.screenshot({path:process.env.DIRECTOR_ANIMATION_QA});
  await button("截图到画布").click();
  await page.getByText("已添加到画布",{exact:true}).waitFor();
  await button("返回画布").click();
  const saved = await (await page.request.get(endpoint)).json();
  const scene = saved.nodes.find(n => n.id === stage.id).data.stage;
  assert.deepEqual(scene.referenceIds,["coast","operator"]);
  assert.ok(scene.objects.some(o => o.shape === "table"));
  assert.equal(scene.objects.find(o => o.id === actor.id).keys.at(-1).position[0],4);
  assert.ok(scene.objects.find(o => o.id === camera.id).keys.length > 2);
  assert.ok(saved.nodes.some(n => n.data.kind === "image" && n.data.title.includes("全景")));
  await page.reload(); await button("打开导演台").click(); await button("动画时间轴").click();
  await button("访客 第 120 帧").click();
  await page.waitForFunction(() => document.querySelector('[aria-label="位置 X"]').value === "4");
  await button("访客 第 120 帧").press("ArrowLeft");
  await button("访客 第 119 帧").waitFor();
  await button("删除当前关键帧").click();
  assert.equal(await button("访客 第 119 帧").count(),0);
  await page.setViewportSize({width:390,height:844});
  await button("运镜").click();
  assert.ok(await page.getByRole("combobox",{name:"运镜方式"}).isVisible());
  await button("收起属性").click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
});

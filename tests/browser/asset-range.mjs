import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, rm } from "node:fs/promises";
import path from "node:path";
import { tmpdir } from "node:os";
import { chromium } from "playwright";
import { createServer } from "vite";
import { imageFixture } from "../fixtures/browser-image.mjs";

test("素材框选可回缩和跨屏，分页、标签和收藏保留选择，确实使用才出现在最近使用", async t => {
  const dir = await mkdtemp(path.join(tmpdir(), "studio-range-"));
  process.env.STUDIO_DATA_DIR = dir;
  t.after(() => rm(dir, { recursive: true, force: true }));
  const vite = await createServer({ server: { port: 0, hmr: false }, logLevel: "error" });
  await vite.listen();
  t.after(() => vite.close());
  const browser = await chromium.launch();
  t.after(() => browser.close());
  const p = await browser.newPage({ viewport: { width: 1360, height: 880 } });
  p.setDefaultTimeout(4500);
  const base = vite.resolvedUrls.local[0];
  for (let i = 0; i < 22; i++) {
    const png = await imageFixture(p, `rgb(${i}, 92, 128)`);
    const name = "角色卡" + i + ".png";
    const res = await p.request.post(base + "api/assets?" + new URLSearchParams({ name }),
      { data: png, headers: { "content-type": "application/octet-stream" } });
    assert.equal(res.status(), 201);
  }
  const board = await (await p.request.post(base + "api/projects", { data: { name: "批量选择" } })).json();
  await p.goto(base + "#project/" + board.id);
  const button = (name) => p.getByRole("button", { name, exact: true });
  const grid = p.locator(".library-batch .asset-grid");
  const card = grid.locator("article");
  const checked = grid.locator("input:checked");
  const status = p.locator(".asset-batch-actions [role=status]");
  await button("素材库").click();
  await button("角色卡").click();
  assert.equal(await card.count(), 20);
  await button("下一页").click();
  assert.equal(await card.count(), 2);
  await card.first().getByRole("checkbox").check();
  await button("上一页").click();
  const box = await card.first().boundingBox();
  const second = await card.nth(1).boundingBox();
  const secondRow = await card.nth(5).boundingBox();
  const x = box.x + 25, y = box.y + 30;
  await p.mouse.move(x, y);
  await p.mouse.down();
  await p.mouse.move(second.x + 25, secondRow.y + 20, { steps: 8 });
  await p.waitForFunction(() => document.querySelectorAll(".asset-grid input:checked").length === 4);
  await p.mouse.move(second.x + 25, y + 8);
  await p.mouse.up();
  assert.equal(await checked.count(), 2);
  assert.equal(await status.textContent(), "已选 3 项");
  assert.equal(await p.locator(".reference-viewer").count(), 0);
  const g = await grid.boundingBox();
  await p.mouse.move(second.x - 5, y + 15);
  await p.mouse.down();
  await p.mouse.move(x, g.y + g.height - 2, { steps: 8 });
  await p.waitForFunction(() => document.querySelector(".library-batch .asset-grid").scrollTop > 150);
  await p.mouse.up();
  assert.ok(await checked.count() > 2);
  await button("全选当前结果").click();
  assert.equal(await status.textContent(), "已选 22 项");
  await button("清空选择").click();
  await button("最近使用").click();
  assert.equal(await card.count(), 0);
  await button("最近使用").click();
  await button("收藏 角色卡21.png").click();
  await button("我的收藏").click();
  await p.waitForFunction(() => document.querySelectorAll(".asset-grid article").length === 1);
  await card.first().getByRole("checkbox").check();
  await button("加入画布（1）").click();
  await button("素材库").click();
  await button("最近使用").click();
  await card.getByText("角色卡21.png", { exact: true }).waitFor();
  assert.equal(await card.count(), 1);
  await p.reload();
  await button("素材库").click();
  await button("我的收藏").click();
  await card.getByText("角色卡21.png", { exact: true }).waitFor();
  await card.getByRole("button", { name: "收藏 角色卡21.png" }).click();
  await card.waitFor({ state: "detached" });

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await mobile.goto(base + "#project/" + board.id);
  await mobile.getByRole("button", { name: "素材库", exact: true }).tap();
  await mobile.getByRole("button", { name: "角色卡", exact: true }).tap();
  const first = await mobile.locator(".asset-actions label").first().boundingBox();
  const next = await mobile.locator(".asset-actions label").nth(1).boundingBox();
  const touch = await mobile.context().newCDPSession(mobile);
  const touchAt = (type, x, y) => touch.send("Input.dispatchTouchEvent", {
    type, touchPoints: type === "touchEnd" ? [] : [{ x, y }],
  });
  await touchAt("touchStart", first.x + 20, first.y + 10);
  await touchAt("touchMove", next.x + 20, next.y + 10);
  await touchAt("touchEnd");
  assert.equal(await mobile.locator(".asset-grid input:checked").count(), 2);
  const thumb = await mobile.locator(".asset-thumb").first().boundingBox();
  await touchAt("touchStart", thumb.x + 30, thumb.y + 40);
  await touchAt("touchMove", thumb.x + 30, thumb.y - 40);
  await touchAt("touchEnd");
  await mobile.waitForFunction(() => document.querySelector(".library-batch .asset-grid").scrollTop > 0);
  assert.equal(await mobile.locator(".asset-grid input:checked").count(), 2);
});

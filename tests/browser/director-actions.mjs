import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { chromium } from "playwright";
import { createServer } from "vite";
import { makeNode } from "../../shared/studio.js";

test("角色动作、关节和场景开关可回读，手动记录、锁定和撤销正确作用于所选角色", async t => {
  const dir = await mkdtemp(path.join(tmpdir(),"director-actions-"));
  process.env.STUDIO_DATA_DIR = dir;
  t.after(()=>rm(dir,{recursive:true,force:true}));
  const vite = await createServer({server:{port:0,hmr:false}, logLevel:"error"});
  await vite.listen(); t.after(()=>vite.close());
  const browser = await chromium.launch({args:["--use-angle=swiftshader","--enable-unsafe-swiftshader"]});
  t.after(()=>browser.close());
  const page = await browser.newPage({viewport:{width:1440,height:850}});
  page.setDefaultTimeout(10000);
  const errors=[]; page.on("pageerror",e=>errors.push(e.message));
  const base=vite.resolvedUrls.local[0], node=makeNode("stage",{x:0,y:0},{title:"试镜"});
  const created = await page.request.post(base+"api/projects",{data:{board:{name:"试镜",nodes:[node],edges:[],order:[]}}});
  const board=await created.json(), endpoint=base+"api/projects/"+board.id;
  const button=name=>page.getByRole("button",{name,exact:true});
  const setting=name=>page.getByRole("switch",{name,exact:true});
  await page.goto(base+"#project/"+board.id);
  await button("打开导演台").click(); await button("动作库").click();
  await page.locator(".ds-action-grid img").first().waitFor();
  await button("交流").click(); await button("挥手").click();
  await button("预览动作").click();
  await button("停止预览").click();
  await page.getByText("关节微调",{exact:true}).click();
  await button("右臂").click(); await page.getByRole("slider",{name:"右肩前举"}).press("ArrowRight");
  assert.equal(await page.getByRole("slider",{name:"右肩前举"}).inputValue(),"1");
  await page.getByText("场景开关",{exact:true}).click();
  await setting("角色标签").check(); await page.locator(".ds-actor-labels span").waitFor();
  await setting("机位监看").uncheck(); assert.equal(await button("放大机位监看").count(),0);
  await setting("显示地面").uncheck(); await setting("网格吸附").check();
  if (process.env.STAGE_ACTION_QA) await page.screenshot({path:process.env.STAGE_ACTION_QA});
  await button("隐藏角色 1").click(); await page.locator(".ds-actor-labels span").waitFor({state:"hidden"});
  await button("撤销").click(); await page.locator(".ds-actor-labels span").waitFor();
  await button("锁定角色 1").click(); assert.ok(await button("点头").isDisabled());
  await button("解锁角色 1").click();
  await button("动画时间轴").click(); await page.getByLabel("时间轴播放头").press("End");
  await button("自动关键帧").click(); await button("点头").click();
  await page.getByRole("alert").filter({hasText:"先点「记录关键帧」"}).waitFor();
  await button("记录关键帧").click(); await button("点头").click();
  await button("循环播放").click(); assert.equal(await button("循环播放").getAttribute("aria-pressed"),"true");
  await page.waitForFunction(()=>document.querySelector(".ds-status")?.textContent==="已保存");
  await button("返回画布").click();
  const stage=(await (await page.request.get(endpoint)).json()).nodes[0].data.stage;
  assert.deepEqual(stage.settings,{labels:true,monitor:false,floor:false,snap:true});
  assert.equal(stage.objects[0].pose,"waving");
  assert.equal(stage.objects[0].joints.rightArm,1);
  assert.equal(stage.objects[0].keys.length,1);
  assert.deepEqual(stage.objects[0].keys[0].joints,{});
  await page.reload(); await button("打开导演台").click();
  await button("动作库").click(); assert.equal(await button("挥手").getAttribute("aria-pressed"),"true");
  await page.setViewportSize({width:390,height:844});
  await button("对象属性").click(); await button("移动").click();
  await button("跑步").click(); assert.equal(await button("跑步").getAttribute("aria-pressed"),"true");
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(errors,[]);
});

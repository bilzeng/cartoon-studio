import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { chromium } from "playwright";
import { createServer } from "vite";
import { imageSize } from "image-size";
import { makeNode } from "../../shared/studio.js";

test("导演台保存调度并从两个机位拍摄到画布", async t => {
  const dir = await mkdtemp(path.join(tmpdir(), "studio-director-"));
  process.env.STUDIO_DATA_DIR = dir;
  t.after(() => rm(dir, { recursive: true, force: true }));
  const vite = await createServer({ server:{ port:0, hmr:false }, logLevel:"error" });
  await vite.listen(); t.after(() => vite.close());
  const browser = await chromium.launch({ args:["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
  t.after(() => browser.close());
  const page = await browser.newPage({viewport:{width:1350,height:800}});
  const errors = [];
  page.on("pageerror", e => errors.push(e.message));
  const base = vite.resolvedUrls.local[0];
  const board = await (await page.request.post(base+"api/projects",{ data:{name:"镜头调度练习"} })).json();
  const endpoint = base+"api/projects/"+board.id;
  await page.goto(base+"#project/"+board.id);
  const button = name => page.getByRole("button",{name,exact:true});
  await button("添加节点").click();
  await button("导演台").click();
  await button("打开导演台").click();
  const dialog = page.getByRole("dialog",{name:"3D 导演台"});
  await dialog.waitFor();
  await button("添加角色").click();
  await page.getByLabel("对象名称").fill("交谈者");
  await page.getByLabel("旋转角度 Y").fill("-34");
  await page.getByLabel("旋转角度 Y").press("Enter");
  await page.getByRole("combobox",{name:"角色姿势"}).click();
  await page.getByRole("option",{name:"倾听"}).click();
  if (process.env.DIRECTOR_QA_IMAGE) await page.screenshot({path:process.env.DIRECTOR_QA_IMAGE});
  await button("机位视角").click();
  await button("截图到画布").click();
  await page.getByText("已添加到画布",{exact:true}).waitFor();
  await button("添加机位").click();
  const surface = await page.getByLabel("三维场景视窗").boundingBox();
  await page.mouse.move(surface.x + 80, surface.y + 140);
  await page.mouse.down();
  await page.mouse.move(surface.x + 170, surface.y + 160, { steps:6 });
  await page.mouse.up();
  await button("机位对齐导演视角").click();
  await page.getByRole("combobox",{name:"取景画幅"}).click();
  await page.getByRole("option",{name:"9:16",exact:true}).click();
  await button("机位视角").click();
  await button("截图到画布").click();
  await page.waitForFunction(() => {
    const button = document.querySelector(".ds-capture");
    return button && !button.disabled && document.querySelector(".ds-feedback")?.textContent.includes("已添加");
  });
  await button("返回画布").click();
  const saved = await (await page.request.get(endpoint)).json();
  const stage = saved.nodes.find(n=>n.data.kind==="stage");
  assert.equal(stage.data.stage.objects.length,4);
  assert.equal(stage.data.stage.ratio,"9:16");
  assert.equal(stage.data.stage.objects.find(o=>o.name==="交谈者").pose,"listening");
  assert.equal(stage.data.stage.objects.find(o=>o.name==="交谈者").rotation[1],-34);
  const frames = saved.nodes.filter(n=>n.data.kind==="image");
  assert.equal(frames.length,2);
  assert.deepEqual(saved.edges.map(e=>[e.source,e.target]),frames.map(n=>[stage.id,n.id]));
  const assets = await (await page.request.get(base+"api/assets")).json();
  for (const [i,frame] of frames.entries()) {
    const asset = assets.find(a=>a.id===frame.data.assetId);
    const png = await (await page.request.get(new URL(asset.url,base).href)).body();
    const {width,height} = imageSize(png);
    assert.deepEqual([width,height],i===0?[1920,1080]:[1080,1920]);
    assert.ok(png.length>16000,"画面有场景内容");
  }
  const framed = stage.data.stage.objects.find(o => o.id === stage.data.stage.cameraId);
  assert.notEqual(framed.position[0],3.25,"环绕后的机位跟随导演视角");
  const input = makeNode("image", {x: -430, y:0}, {title:"海岸背景", assetId:"coast"});
  const attached = await page.request.put(endpoint, { data:{...saved,
    nodes:[...saved.nodes,input], edges:[...saved.edges,{id:"coast-stage",source:input.id,target:stage.id}]} });
  assert.equal(attached.status(),200);
  await page.reload();
  await button("打开导演台").click();
  await button("交谈者").click();
  assert.equal(await page.getByLabel("旋转角度 Y").inputValue(),"-34");
  await page.getByRole("combobox",{name:"场景背景"}).click();
  const coast = assets.find(a=>a.id==="coast");
  await page.getByRole("option",{name:coast.name,exact:true}).click();
  await page.waitForFunction(()=>document.querySelector(".ds-status")?.textContent==="已保存");
  const linked = await (await page.request.get(endpoint)).json();
  assert.equal(linked.nodes.find(n=>n.id===stage.id).data.stage.backgroundId,"coast");
  await page.setViewportSize({width:390,height:844});
  await button("对象属性").click();
  assert.ok(await page.getByLabel("对象名称").isVisible());
  await button("收起属性").click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.keyboard.press("Escape");
  await dialog.waitFor({state:"detached"});
  assert.deepEqual(errors,[]);
});

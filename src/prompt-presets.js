export function promptPresets(kind, verbatim) {
  const groups = kind === "audio" ? (verbatim ? voiceGroup : audioGroups)
    : kind === "video" ? videoGroups
      : kind === "shot" ? { ...imageGroups, ...videoGroups } : imageGroups;
  return Object.entries(groups).flatMap(([category, entries]) =>
    entries.map(([title, text]) => ({ id: category + "/" + title, category, title, text })));
}
